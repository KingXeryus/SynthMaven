"""Compile researched four-part recipes through the firmware's real preset loader."""
import argparse,json,subprocess,os
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
a=argparse.ArgumentParser();a.add_argument('--check',action='store_true');args=a.parse_args()
m=json.loads((ROOT/'assets/programs/recipes.json').read_text());rows=m['programs'];assert len(rows)==8
build=ROOT/'build/gen';build.mkdir(parents=True,exist_ok=True)
scene_offsets='static const int8_t FACTORY_SCENE_LEVEL[8][4] = '+json.dumps([r.get('scene_level_offsets',[0,0,0,0]) for r in rows]).replace('[','{').replace(']','}')+';\n'
body=scene_offsets+'#define FACTORY_RECIPE_NAMES '+json.dumps([r['name'] for r in rows]).replace('[','{').replace(']','}')+'\n/* Generated recipe inputs. */\nstatic void factory_recipe(uint32_t slot){\n track_t *t;switch(slot){\n'
for i,row in enumerate(rows):
 assert 0<len(row['name'])<=12 and row['name'].isascii() and len(row['layers'])==4
 body+=f'case {i}:\n'
 for j,l in enumerate(row['layers']):
  body+=f' t=&trk[{j}];set_engine_of(t,{l["engine"]});apply_preset_to(t,{l["preset"]});\n'
  params={'P_LEVEL':l['level'],'P_PAN':l['pan'],'P_VOICE':l['voice'],'P_REV':l['reverb'],'P_CHOR':l['chorus'],'P_DLY':l['delay'],'P_TFLT':l['highpass'],'P_DIST':0,'P_AMODE':0,'P_AHOLD':0,'P_CHORD':0,'P_QUANT':0,'P_SPREAD':0,'P_VINT':4,'P_LD_PIT':0,'P_LD_AMP':0,'P_SPICE':0,'P_DICE':0,'P_GLIDE':0,'P_MUTE':0,'P_MWDST':'MD_VIB','P_ATDST':'MD_VIB'}
  if l.get('envelope'):params.update(zip(['P_ATK','P_DEC','P_SUS','P_REL'],l['envelope']))
  params.update(l.get('params',{}))
  for k,v in params.items():assert k.startswith('P_');body+=f' t->p[{k}]={v};\n'
  body+=f' t->p[P_ED_FX]+={row["trim_half_db"]+l.get("trim_half_db",0)};program_route[{j}]=(program_route_t){{1,0,0,60,{l["transpose"]}}};\n'
  body+=f' program_solo_gain[{j}]={l.get("solo_gain_db",0)+1};\n'
  if 'split' in row:body+=f' program_route[{j}].split=1;program_route[{j}].upper={int(j>=2)};program_route[{j}].point={row["split"]};\n'
 body+=' break;\n'
body+=' }\n}\n'
(build/'factory_program_recipes.h').write_text(body)
cc=[os.environ.get('CC','cc'),'-O2','-w','-DSYNTHMAVEN_SYNTH=1','-Ibuild/gen','-Ifirmware/src','-Ifirmware/hal','tests/factory_program_generator.c','-o','build/host/factory_program_generator','-lm']
subprocess.run(cc,cwd=ROOT,check=True);subprocess.run(['build/host/factory_program_generator'],cwd=ROOT,check=True)
raw=(ROOT/'build/host/factory-programs.bin').read_bytes();assert len(raw)%8==0;size=len(raw)//8
header='#pragma once\n/* Generated by tools/gen_factory_programs.py; recipes: assets/programs/recipes.json. */\n#define SM_FACTORY_PROGRAM_COUNT 8u\n#define SM_FACTORY_PROGRAM_NAMES '+json.dumps([r['name'] for r in rows]).replace('[','{').replace(']','}')+'\n'
header+=f'_Static_assert(sizeof(program_packed_t)=={size}u,"factory program storage layout");\nstatic const union {{program_packed_t packed;uint8_t bytes[sizeof(program_packed_t)];}} SM_FACTORY_PROGRAMS[8]={{\n'
for i in range(8):header+=' {.bytes={'+','.join(map(str,raw[i*size:(i+1)*size]))+'}},\n'
header+='};\n'
catalog=json.loads((ROOT/'build/host/factory-programs.json').read_text())
for i,row in enumerate(rows):catalog[i].update({k:row[k] for k in ['name','style','play']});catalog[i]['roles']=[l['role'] for l in row['layers']]
outputs={'firmware/src/factory_programs.h':header,'assets/programs/catalog.json':json.dumps(catalog,indent=2)+'\n'}
for name,data in outputs.items():
 p=ROOT/name
 if args.check:assert p.read_text()==data,name+' stale: regenerate factory programs'
 else:p.write_text(data)
print(f'8 four-part programs, four scenes each, {size} bytes each: PASS')
