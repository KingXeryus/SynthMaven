#!/usr/bin/env python3
"""Stereo BS.1770-4 gated loudness and 4x oversampled peak audit of all factory sounds."""
import argparse,csv,json
from pathlib import Path
import numpy as np
from scipy.signal import lfilter,resample_poly
FS=44100;SEG=(FS*9//2)//32*32+(FS//4)//32*32
# Sample-rate-correct DeMan design of the BS.1770 K-weighting stages.
# Reference: pyloudnorm IIRfilter.generate_coefficients / Meter.filter_class (DeMan).
k=np.tan(np.pi*1681.974450955533/FS);q=.7071752369554196;vh=10**(3.999843853973347/20);vb=vh**.4996667741545416;a=1+k/q+k*k
B1=[(vh+vb*k/q+k*k)/a,2*(k*k-vh)/a,(vh-vb*k/q+k*k)/a];A1=[1,2*(k*k-1)/a,(1-k/q+k*k)/a]
k=np.tan(np.pi*38.13547087602444/FS);q=.5003270373238773;a=1+k/q+k*k
B2=[1,-2,1];A2=[1,2*(k*k-1)/a,(1-k/q+k*k)/a]
def measure(x):
 y=lfilter(B2,A2,lfilter(B1,A1,x,axis=0),axis=0)
 energy=np.sum(y*y,axis=1);w=int(.4*FS);h=int(.1*FS)
 blocks=np.array([np.mean(energy[i:i+w]) for i in range(0,len(x)-w+1,h)])
 gated=blocks[blocks>10**((-70+.691)/10)]
 if not len(gated):return None,None
 relative=np.mean(gated)*.1;gated=gated[gated>relative]
 loud=-.691+10*np.log10(np.mean(gated));peak=np.max(np.abs(resample_poly(x,4,1,axis=0)))
 return float(loud),float(20*np.log10(max(peak,1e-12)))
def main():
 ap=argparse.ArgumentParser();ap.add_argument('raw');ap.add_argument('catalog');ap.add_argument('--out',required=True);ap.add_argument('--partial',action='store_true');ap.add_argument('--calibrate',action='store_true');ap.add_argument('--verify',action='store_true');ap.add_argument('--target',type=float,default=-14.0);a=ap.parse_args()
 rows=[l.split(None,4) for l in Path(a.catalog).read_text().splitlines()];assert rows and (a.partial or len(rows)==557)
 data=np.memmap(a.raw,dtype='<i4',mode='r');assert len(data)==len(rows)*SEG*2
 result=[]
 for i,(e,p,role,trim,name) in enumerate(rows):
  x=np.asarray(data[i*SEG*2:(i+1)*SEG*2],dtype=np.float64).reshape(-1,2)/32768
  loud,peak=measure(x);result.append(dict(engine=int(e),preset=int(p),role=int(role),trim=int(trim),name=name,lufs=loud,true_peak_dbtp=peak))
 Path(a.out).write_text(json.dumps(result,indent=2)+'\n')
 if a.calibrate:
  header=Path(__file__).resolve().parents[1]/'firmware/src/factory_levels.h'
  old=header.read_text();maxp=max(r['preset'] for r in result)+1;table=[[0]*maxp for _ in range(23)]
  for r in result:
   value=r['trim'] if r['lufs'] is None else round(r['trim']+2*(a.target-r['lufs']))
   if not -64<=value<=127:raise ValueError('Trim out of range: '+r['name'])
   table[r['engine']][r['preset']]=value
  gain=old[old.index('static const uint32_t SM_TRIM_GAIN_Q12'):]
  header.write_text('/* Generated by tools/match_factory_levels.py: 557 entries, stereo BS.1770-4, target '+str(a.target)+' LUFS. USER WT remains an uncalibrated user-data slot. */\n#define SM_LEVEL_MAX '+str(maxp)+'u\nstatic const int8_t SM_FACTORY_LEVEL[23][SM_LEVEL_MAX] = {\n'+''.join(' {'+','.join(map(str,row))+'},\n' for row in table)+'};\n'+gain)

 audible=[r for r in result if r['lufs'] is not None]
 if a.verify:
  assert not a.calibrate, 'Verification must not alter calibration'
  assert len({(r['engine'],r['preset']) for r in result})==557
  assert len(audible)==556 and [r['name'] for r in result if r['lufs'] is None]==['USER WT']
  # 2.2.1 reports loudness without enforcing the reverted target.
  assert all(r['true_peak_dbtp']<=-1 for r in audible), 'Factory true peak exceeds -1 dBTP'
  print('PASS: 556 audible sounds; one intentionally silent USER WT; all true peaks below -1 dBTP')
 print('Measured',len(result),'audible',len(audible));print('LUFS range',min(r['lufs'] for r in audible),max(r['lufs'] for r in audible));print('Peak max',max(r['true_peak_dbtp'] for r in audible));print('Quietest',sorted(audible,key=lambda r:r['lufs'])[:8]);print('Silent',[r['name'] for r in result if r['lufs'] is None])
if __name__=='__main__':main()
