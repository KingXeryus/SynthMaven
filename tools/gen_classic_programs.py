#!/usr/bin/env python3
"""Map preserved SynthMaven factory program parameters by name, never numeric ID."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
data=json.loads((ROOT/'assets/legacy-synthmaven/catalogue.json').read_text())
fields='P_ATK P_DEC P_SUS P_REL P_ED_FLT P_ED_PIT P_ED_SHP P_LRATE P_LWAVE P_LPHASE P_LFADE P_LD_PIT P_LD_FLT P_LD_SHP P_LD_AMP P_VOICE P_GLIDE P_TRANS P_PAN P_GLMODE P_PRIO P_ALLOC P_DETUNE'.split()+[f'P_E{i}' for i in range(8)]
engines={0:23,1:24,5:25,12:22,15:26,21:27}
out=['/* SPDX-License-Identifier: GPL-3.0-only */\n/* Generated by tools/gen_classic_programs.py from the preserved factory capture. */\n', 'typedef struct {uint8_t engine,preset,level;int8_t p[32];} sm_classic_program_part_t;\nstatic const sm_classic_program_part_t SM_CLASSIC_PROGRAMS[8][4]={\n']
for program in data['programs']:
 out.append('{\n')
 for part in program['parts']:
  p=dict(zip(data['parameter_names'],part['p']));values=[p[f] for f in fields]+[p['P_SLPAT']]
  values[fields.index('P_TRANS')]=max(-48,min(48,p['P_TRANS']+part['route'][4]))
  values[fields.index('P_VOICE')]=min(p['P_VOICE'],3)
  out.append('{'+f"{engines[part['engine']]},{part['preset']},{p['P_LEVEL']},"+'{'+','.join(map(str,values))+'}},\n')
 out.append('},\n')
out.append('};\nstatic const uint8_t SM_CLASSIC_PIANO_PATCH[128]={'+','.join(map(str,data['programs'][0]['parts'][0]['patch'][:128]))+'};\n')
(ROOT/'firmware/src/classic_programs.h').write_text(''.join(out))
