"""Programmatic loudness compensation: match every factory sound to the DX7 program.

Input: the output of `loudness_measure sounds` (tests/loudness_measure.c), measured with the table now in the firmware.
Output: firmware/src/loudness_comp.h, a 4-bit gain per preset: 1.5 dB steps from -6 to +12 dB, then +15, +18 and +24 dB.
Compression makes the response non-linear, so run measure + generate a few times: each pass corrects the last one.

  gen_loudness_comp.py SOUNDS.tsv
"""
import re
import sys
from pathlib import Path

NENGINES, UNITY = 32, 4
TARGET = -11.14                    # dB: P1 DX7 E.PIANO as tests/loudness_measure.c measured it before any compensation
DB = [-6, -4.5, -3, -1.5, 0, 1.5, 3, 4.5, 6, 7.5, 9, 10.5, 12, 15, 18, 24]


def main():
    sounds = [l.rstrip("\n").split("\t") for l in open(sys.argv[1]) if l.strip()]
    target = TARGET
    out = Path(__file__).resolve().parents[1] / "firmware/src/loudness_comp.h"
    old = out.read_text()
    old_off = [int(x) for x in re.search(r"SM_LOUD_OFF\[NENGINES\]=\{(.*?)\}", old)[1].split(",")]
    old_data = [int(x) for x in re.search(r"SM_LOUD\[\] PRESET_TABLE=\{(.*?)\}", old)[1].split(",")]
    def current(e, p):
        at = old_off[e] + p
        return DB[(old_data[at // 2] >> (4 * (at & 1))) & 15] if len(old_off) > e and at // 2 < len(old_data) else 0
    counts, rows = [0] * NENGINES, {}
    for e, p, _name, v, _peak in sounds:
        counts[int(e)] = max(counts[int(e)], int(p) + 1)
        rows[(int(e), int(p))] = float(v)
    off, at = [], 0
    for c in counts:
        off.append(at)
        at += c
    nib, limited = [UNITY] * at, 0
    for (e, p), v in rows.items():
        want = current(e, p) + target - v
        limited += not DB[0] - 1 <= want <= DB[-1] + 1
        nib[off[e] + p] = min(range(16), key=lambda i: abs(DB[i] - want))
    data = [nib[i] | (nib[i + 1] if i + 1 < at else UNITY) << 4 for i in range(0, at, 2)]
    q12 = [round(4096 * 10 ** (d / 20)) for d in DB]
    lines = ["/* Generated by tools/gen_loudness_comp.py from tests/loudness_measure.c: do not edit. */",
             f"/* Target: P1 DX7 E.PIANO, {target:.2f} dB. {len(rows)} sounds, {limited} at the range's limit. */",
             f"#define SM_LOUD_UNITY {UNITY}u",
             f"static const uint16_t SM_LOUD_OFF[NENGINES]={{{','.join(map(str, off))}}};",
             f"static const uint8_t SM_LOUD[] PRESET_TABLE={{{','.join(map(str, data))}}};",
             f"static const uint16_t SM_LOUD_Q12[16]={{{','.join(map(str, q12))}}};", ""]
    out.write_text("\n".join(lines))
    print(f"{len(rows)} sounds, target {target:.2f}, {limited} limited, {len(data)} table bytes")


if __name__ == "__main__":
    main()
