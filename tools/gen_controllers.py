"""Compile the sourced controller family catalogue into bounded USB identity rules."""
import argparse,json
from pathlib import Path
root=Path(__file__).resolve().parents[1];ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');args=ap.parse_args()
rows=json.loads((root/'assets/controllers/catalog.json').read_text());out='/* Generated by tools/gen_controllers.py; edit assets/controllers/catalog.json. */\n#pragma once\ntypedef struct {uint16_t vid;const char *match,*family;uint8_t daw;} ct_profile_t;\nstatic const ct_profile_t CT_PROFILE[]={\n'
seen=set()
for r in rows:
 assert r['source'].startswith('https://') and r['models'] and len(r['family'])<24 and 0<r['vid']<65536 and r['daw'] in (0,1,255)
 for pattern in r['patterns']:
  assert pattern.isalnum() and pattern.islower() and (r['vid'],pattern) not in seen;seen.add((r['vid'],pattern))
  out+=f' {{0x{r["vid"]:04x},"{pattern}","{r["family"]}",{r["daw"]}}},\n'
out+='};\n';p=root/'firmware/src/controller_profiles.h'
if args.check:assert p.read_text()==out,'regenerate controller profiles'
else:p.write_text(out)
print(f'{len(rows)} sourced USB controller families / {len(seen)} identity rules PASS')
