"""Compact the original 0.2 desktop's world collection without storing 208 full patches."""
import json,collections,re
from oriental_selection import select_presets
from pathlib import Path
root=Path(__file__).resolve().parents[1]
items=json.loads((root/'assets/oriental/software-0.2.json').read_text())
items=select_presets(items)
assert len(items)==88
original_names=json.loads((root/"assets/oriental/original-names.json").read_text())
for x in items:
 assert len(original_names[x["engine"]])==x["originalCount"]
 assert original_names[x["engine"]][x["basePreset"]]==x["baseName"]
rows=[items[i:i+2] for i in range(0,len(items),2)]
assert all(len({x['engine'] for x in r})==1 and len({x['basePreset'] for x in r})==1 for r in rows)
data=[];ops=[]
for p in range(126):
 if all(x['values'][p]==x['baseValues'][p] for x in items):continue
 patterns=[tuple(x['values'][p] for x in row) for row in rows]
 unique=list(dict.fromkeys(patterns));offset=len(data)
 if len(unique)==1:mode=0;data.extend(unique[0])
 elif all(len(set(pattern))==1 for pattern in patterns):mode=1;data.extend(pattern[0] for pattern in patterns)
 elif len(unique)==2:
  mode=2;data.extend(unique[0]);data.extend(unique[1]);data.extend(sum((1<<(w%8)) for w in range(n*8,min(n*8+8,len(rows))) if patterns[w]==unique[1]) for n in range((len(rows)+7)//8))
 else:mode=3;data.extend(v for pattern in patterns for v in pattern)
 assert all(-128<=n<=255 for n in data[offset:]);data[offset:]=[n-256 if n>127 else n for n in data[offset:]];ops.append((p,mode,offset))
short=[];world=[];engine_local=collections.Counter();web=[]
for w,row in enumerate(rows):
 x=row[0];name=x['name'].removeprefix('OR ').rsplit(' / ',1)[0]
 abbr=name.upper()[:10].rstrip();assert abbr not in short,abbr;short.append(abbr)
 world.append((abbr,x['engine'],x['basePreset']))
 # Original engine lengths are emitted by the export so IDs append stably.
 base_count=x['originalCount'];start=base_count+engine_local[x['engine']]*2;engine_local[x['engine']]+=1
 assert start+1<255
 for v,item in enumerate(row):web.append({'name':item['name'],'shortName':abbr+' '+('DE'[v]),'engine':x['engine'],'preset':start+v,'basePreset':x['basePreset'],'values':item['values'][:126]})
# Sound recipes retain desktop synthesis values; only output trim is calibrated for the FM1.
levels=[list(map(int,row.split(','))) for row in re.findall(r' \{([^{}]+)\}',(root/'firmware/src/factory_levels.h').read_text())]
for sound in web:sound['values'][8]=levels[sound['engine']][sound['preset']]
name_offsets=[];name_pos=0
for name,_,_ in world:name_offsets.append(name_pos);name_pos+=len(name)+1
lines=['/* Generated by tools/gen_oriental.py; original SynthMaven recipes, GPL-3.0-only. */','#pragma once', '#define SM_OR_COUNT 88u', '#define SM_OR_WORLDS 44u', 'static const char SM_OR_NAMES[] = '+ ' '.join((json.dumps(n)[:-1]+'\\0"') for n,_,_ in world)+';', 'static const struct { uint16_t name; uint8_t engine,base; } SM_OR_WORLD[] = {']
lines += [f'{{{name_offsets[i]},{e},{b}}},' for i,(n,e,b) in enumerate(world)];lines+=['};','static const int8_t SM_OR_DATA[] = {']
lines += [','.join(map(str,data[i:i+24]))+',' for i in range(0,len(data),24)];lines+=['};','static const struct { uint8_t id,mode; uint16_t offset; } SM_OR_OP[] = {']
lines += [f'{{{p},{m},{o}}},' for p,m,o in ops];lines+=['};']
(root/'firmware/src/oriental_factory.h').write_text('\n'.join(lines)+'\n')
(root/'assets/oriental/editor.json').write_text(json.dumps(web,separators=(',',':'))+'\n')
html=root/'web/editor.html';s=html.read_text();begin='/* ORIENTAL_STOCK_BEGIN */';end='/* ORIENTAL_STOCK_END */';block=begin+'\nconst ORIENTAL_LAYOUT = '+json.dumps(json.loads((root/'assets/oriental/layout.json').read_text()),separators=(',',':'))+';\nconst ORIENTAL_NATIVE_NAMES = '+json.dumps(json.loads((root/'assets/oriental/original-names.json').read_text()),separators=(',',':'))+';\nconst ORIENTAL_STOCK = '+json.dumps(web,separators=(',',':'))+';\n'+end
if begin in s:s=s[:s.index(begin)]+block+s[s.index(end)+len(end):]
else:s=s.replace('/* KORG_STOCK_BEGIN */',block+'\n/* KORG_STOCK_BEGIN */',1)
html.write_text(s)
print(f'Oriental bank: {len(items)} sounds, {len(world)} recipes, {len(ops)} columns, {len(data)} packed value bytes, {sum(len(n)+1 for n,_,_ in world)} name bytes')
