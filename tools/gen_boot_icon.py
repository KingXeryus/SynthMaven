#!/usr/bin/env python3
"""Encode the shared Hybrid app artwork as a small RGB565 startup image."""
from pathlib import Path
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
im=Image.open(ROOT/'ios/Branding/hybrid-app-icon.png').convert('RGB').resize((96,96),Image.Resampling.LANCZOS).quantize(colors=4)
pal=im.getpalette();colors=[]
for i in range(4):
 r,g,b=pal[i*3:i*3+3];c=((r>>3)<<11)|((g>>2)<<5)|(b>>3);colors.append(((c&255)<<8)|(c>>8))
# RGB565 can merge quantizer entries. Canonicalize those identical colours
# before RLE; this is pixel-identical on the display, not downsampling.
px=[colors.index(colors[v]) for v in im.getdata()];runs=[]
for y in range(96):
 row=px[y*96:(y+1)*96];i=0
 while i<96:
  j=i+1
  while j<96 and j-i<64 and row[j]==row[i]:j+=1
  runs.append(((j-i-1)<<2)|row[i]);i=j
out='/* Shared Hybrid app artwork; generated by tools/gen_boot_icon.py. */\nstatic const uint16_t SM_BOOT_PALETTE[4]={'+','.join(map(str,colors))+'};\nstatic const uint8_t SM_BOOT_RLE[]={'+','.join(map(str,runs))+'};\n'
(ROOT/'firmware/src/sm_boot_icon.h').write_text(out)
print('Startup artwork:',len(runs)+8,'flash bytes; no permanent RAM')
