#!/usr/bin/env python3
"""Build the illustrated PDF from the same reference shipped on the installer.

Requires reportlab and beautifulsoup4. Screenshots are generated by ui_render
and synchronized by manual_shots.py; no independent copy of guide prose exists.
"""
import argparse
from html import escape
from pathlib import Path
import re
from bs4 import BeautifulSoup, NavigableString, Tag
from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.pagesizes import A4
from reportlab.platypus import (SimpleDocTemplate, Paragraph, Spacer, Image,
                               LongTable, TableStyle, PageBreak, KeepTogether)

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--version', default='3.5.1')
    parser.add_argument('--output', type=Path, default=ROOT/'output/pdf/SynthMaven-3.5.1-User-Guide.pdf')
    args = parser.parse_args()
    source = ROOT/'web/manual/index.html'
    soup = BeautifulSoup(source.read_text(), 'html.parser')
    styles = getSampleStyleSheet()
    styles['BodyText'].fontSize = 9.5
    styles['BodyText'].leading = 14
    styles['BodyText'].spaceAfter = 7
    styles['Heading1'].textColor = colors.HexColor('#c41624')
    styles['Heading1'].spaceBefore = 16
    styles['Heading1'].keepWithNext = True
    styles['Heading2'].keepWithNext = True
    styles['Heading2'].fontSize = 13
    styles['Heading2'].leading = 17
    styles['Heading2'].spaceBefore = 12
    styles.add(ParagraphStyle('CaptionSM', parent=styles['BodyText'], fontSize=8,
                             leading=11, textColor=colors.HexColor('#555b65'), alignment=TA_CENTER))
    styles.add(ParagraphStyle('CellSM', parent=styles['BodyText'], fontSize=8, leading=11, spaceAfter=2))
    width = A4[0]-88

    def inline(node):
        if isinstance(node, NavigableString):
            return escape(re.sub(r'\s+', ' ', str(node)).replace('−','-').replace('–','-').replace('—',' - '))
        if not isinstance(node, Tag):
            return ''
        body = ''.join(inline(c) for c in node.children)
        if node.name in ('b','strong','kbd','th'): return '<b>'+body+'</b>'
        if node.name in ('i','em'): return '<i>'+body+'</i>'
        if node.name == 'br': return '<br/>'
        if node.name == 'code': return '<font name="Courier">'+body+'</font>'
        if node.name == 'a' and str(node.get('href','')).startswith('https://'):
            return '<link href="'+escape(node['href'],quote=True)+'" color="#244b78">'+body+'</link>'
        return body

    def paragraph(node, style='BodyText', prefix=''):
        return Paragraph(prefix+inline(node), styles[style])

    def walk(node):
        output=[]
        for child in node.children:
            if not isinstance(child,Tag): continue
            name=child.name
            if name in ('h2','h3','h4'):
                output.append(paragraph(child,'Heading1' if name=='h2' else 'Heading2'))
            elif name=='p': output.append(paragraph(child))
            elif name in ('ol','ul'):
                for i,li in enumerate(child.find_all('li',recursive=False)):
                    output.append(paragraph(li,prefix=f'<b>{i+1}.</b> ' if name=='ol' else '• '))
            elif name=='figure':
                image=child.find('img'); caption=child.find('figcaption')
                if image:
                    path=source.parent/image['src']
                    if not path.is_file(): raise FileNotFoundError(path)
                    shot=Image(str(path))
                    ratio=shot.imageHeight/shot.imageWidth
                    shot.drawWidth=width if image['src'].startswith('editor-') else 150
                    shot.drawHeight=shot.drawWidth*ratio
                    items=[shot]
                    if caption: items.append(paragraph(caption,'CaptionSM'))
                    items.append(Spacer(1,8));output.append(KeepTogether(items))
            elif name=='table':
                rows=[]
                for row in child.find_all('tr'):
                    rows.append([paragraph(cell,'CellSM') for cell in row.find_all(['td','th'],recursive=False)])
                if rows:
                    columns=max(map(len,rows))
                    for row in rows: row.extend(['']*(columns-len(row)))
                    widths=[width/columns]*columns
                    if columns==2: widths=[width*.28,width*.72]
                    table=LongTable(rows,colWidths=widths,repeatRows=1,hAlign='LEFT')
                    table.setStyle(TableStyle([('VALIGN',(0,0),(-1,-1),'TOP'),
                        ('BACKGROUND',(0,0),(-1,0),colors.HexColor('#e7eaf0')),
                        ('LINEBELOW',(0,0),(-1,0),.7,colors.HexColor('#c41624')),
                        ('LINEBELOW',(0,1),(-1,-1),.25,colors.HexColor('#d9dce1')),
                        ('LEFTPADDING',(0,0),(-1,-1),6),('RIGHTPADDING',(0,0),(-1,-1),6),
                        ('TOPPADDING',(0,0),(-1,-1),5),('BOTTOMPADDING',(0,0),(-1,-1),5)]))
                    output.extend([table,Spacer(1,10)])
            elif name=='pre': output.append(paragraph(child,'CellSM'))
            elif name not in ('script','style','nav'): output.extend(walk(child))
        return output

    story=[Spacer(1,90),Paragraph('SYNTHMAVEN',styles['Title']),
           Paragraph(f'{escape(args.version)} · FM-1 user guide',styles['Heading1']),
           Paragraph('Melodee-based firmware · USB web and iPad editor',styles['BodyText']),
           Spacer(1,20),Paragraph('Programs, layers, microtuning, controllers and the complete engine and sequencer reference.',styles['BodyText']),
           Paragraph('Back up before flashing. Installation resets user settings and musical storage. Bluetooth is not included in this USB-first build.',styles['BodyText']),
           PageBreak()]
    story.append(Paragraph('Contents',styles['Heading1']))
    for heading in soup.select('article > section > h2'):
        story.append(paragraph(heading))
    story.append(PageBreak())
    story.extend(walk(soup.select_one('article')))
    def footer(canvas,doc):
        canvas.saveState();canvas.setStrokeColor(colors.HexColor('#c41624'))
        canvas.line(44,38,A4[0]-44,38);canvas.setFont('Helvetica',8)
        canvas.setFillColor(colors.HexColor('#555b65'))
        canvas.drawString(44,25,f'SynthMaven {args.version} | FM-1')
        canvas.drawRightString(A4[0]-44,25,str(doc.page));canvas.restoreState()
    args.output.parent.mkdir(parents=True,exist_ok=True)
    doc=SimpleDocTemplate(str(args.output),pagesize=A4,leftMargin=44,rightMargin=44,
                          topMargin=42,bottomMargin=52,title=f'SynthMaven {args.version} User Guide',author='SynthMaven')
    doc.build(story,onFirstPage=footer,onLaterPages=footer)
    print(args.output)


if __name__=='__main__': main()
