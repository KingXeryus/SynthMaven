#!/usr/bin/env python3
"""Losslessly pack HYBRID factory bytes from the host descriptor dump.
Each patch stores a 128-bit difference mask and bytes differing from a shared
modal patch. Bounded decoding requires no heap or decompression workspace.
The original attributed patch definitions remain the verification source.
"""
import collections,json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
patches=json.loads((root/'build/host/desc.json').read_text())['HYBRID_PK']
assert all(len(p)==128 for p in patches)
base=[collections.Counter(p[i] for p in patches).most_common(1)[0][0] for i in range(128)]
packed=[];offsets=[]
for patch in patches:
 offsets.append(len(packed));mask=[0]*16;values=[]
 for i,v in enumerate(patch):
  if v!=base[i]:mask[i//8]|=1<<(i%8);values.append(v)
 packed+=mask+values
out='/* SPDX-License-Identifier: GPL-3.0-only\n * Lossless encoding of hybrid_patches.h (Copyright 2026 3dSam).\n * Generated by tools/gen_hybrid_factory_pack.py; do not edit. */\n'
for typ,name,values in [('uint8_t','HY_PACK_BASE',base),('uint16_t','HY_PACK_OFF',offsets),('uint8_t','HY_PACK_DATA',packed)]:
 out+=f'static const {typ} {name}[]={{'+','.join(map(str,values))+'};\n'
out+='''static void hy_factory_read(uint32_t slot,hy_patch_t *patch)
{
    if(slot>=HY_NFACTORY)slot=0;
    const uint8_t *mask=HY_PACK_DATA+HY_PACK_OFF[slot],*values=mask+16;
    uint8_t *dest=(uint8_t *)patch;
    for(uint32_t i=0;i<sizeof(*patch);i++)dest[i]=(mask[i/8]&(1u<<(i%8)))?*values++:HY_PACK_BASE[i];
}
_Static_assert(sizeof(hy_patch_t)==128,"packed factory patch width");
_Static_assert(NELEM(HY_PACK_OFF)==HY_NFACTORY,"packed factory patch count");
'''
(root/'firmware/src/hybrid_factory_pack.h').write_text(out)
print(f'{len(patches)*128} -> {len(base)+len(offsets)*2+len(packed)} bytes, lossless')
