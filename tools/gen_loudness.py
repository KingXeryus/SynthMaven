"""Reproduce fixed gain/interpolation tables and explicit transient profiles."""
from pathlib import Path
import argparse,json,numpy as np
from scipy.signal import firwin
ROOT=Path(__file__).resolve().parents[1]
a=argparse.ArgumentParser();a.add_argument('--check',action='store_true');args=a.parse_args()
cfg=json.loads((ROOT/'assets/loudness.json').read_text());gains=[round(4096*10**(v/20)) for v in range(64)];h=firwin(81,.25,window=('kaiser',5))*4
phases=[np.rint(h[p::4]*32768).astype(int).tolist() for p in range(1,4)]
assert max(sum(abs(c) for c in row) for row in phases)<73728
profile=[[0]*105 for _ in range(23)]
for e,p in cfg['transient_presets']:profile[e][p]=1
s='/* Generated by tools/gen_loudness.py from assets/loudness.json. No realtime loudness follower. */\n#pragma once\n#define SM_TARGET_LUFS (-14)\n'
s+='static const uint32_t SM_SOLO_GAIN_Q12[64]={'+','.join(map(str,gains))+'};\n'
s+='/* 4x Kaiser interpolation, matching the release true-peak meter. */\nstatic const int16_t SM_TP_Q15[3][20]={\n'+''.join(' {'+','.join(map(str,row))+'},\n' for row in phases)+'};\n'
s+='/* Pitch-aware recovery for explicit calibrated transient presets. */\nstatic const uint8_t SM_FACTORY_TRANSIENT[23][105]={\n'+''.join(' {'+','.join(map(str,row))+'},\n' for row in profile)+'};\n'
roll=[[0]*105 for _ in range(23)]
for e,p in cfg['roll_presets']:roll[e][p]=1
s+='/* Explicit note-density reference, independent from limiter recovery profiles. */\nstatic const uint8_t SM_FACTORY_ROLL[23][105]={\n'+''.join(' {'+','.join(map(str,row))+'},\n' for row in roll)+'};\n'
p=ROOT/'firmware/src/loudness.h'
if args.check:assert p.read_text()==s,'loudness tables stale'
else:p.write_text(s)
print('Loudness tables: 4x interpolation, bounded coefficients, fixed solo gains and transient profiles PASS')
