#!/usr/bin/env python3
"""Encode verified factory preference assets sparsely for the constrained flash image."""
from pathlib import Path
root=Path(__file__).resolve().parents[1]
text='/* SPDX-License-Identifier: GPL-3.0-only */\n/* Generated by tools/gen_factory_settings.py; verified user backup 2026-10-30. */\n'
for label,size in [('SETTINGS',604),('CONFIG',384)]:
 data=(root/f'assets/factory/{label.lower()}-3.5.bin').read_bytes()
 assert len(data)==size
 pairs=[(i,x) for i,x in enumerate(data) if x]
 encoded=[v for i,x in pairs for v in (i&255,i>>8,x)]
 restored=bytearray(size)
 for j in range(0,len(encoded),3):restored[encoded[j]|encoded[j+1]<<8]=encoded[j+2]
 assert restored==data
 text+=f'#define SM_FACTORY_{label}_SIZE {size}u\nstatic const uint8_t SM_FACTORY_{label}[]={{'+','.join(map(str,encoded))+'};\n'
text+='''static void sm_factory_unpack(void *dst,uint32_t size,const uint8_t *src,uint32_t bytes)
{
    uint8_t *out=dst;memset(out,0,size);
    for(uint32_t i=0;i+2<bytes;i+=3){uint32_t at=src[i]|((uint32_t)src[i+1]<<8);if(at<size)out[at]=src[i+2];}
}
'''
(root/'firmware/src/factory_settings.h').write_text(text)
